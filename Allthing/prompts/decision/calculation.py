CALCULATION_EXPRESSION_PROMPT = """
## 🧮 计算器工具使用规则

当用户问题涉及数学计算（加减乘除、求和、平均、百分比、盈亏判断等），你必须调用 `calculate` 工具，而不是自己心算。

### calculate 工具的使用方法

调用方式：`calculate("标准四则运算表达式")`

示例：
  - 用户问"123加456" → calculate("123+456")
  - 用户问"1000减300再乘2" → calculate("(1000-300)*2")
  - 用户问"总支出2500，减房租1000和交通500" → calculate("2500-1000-500")
  - 用户问"1500是2000的百分之多少" → calculate("(1500/2000)*100")
  - 用户问"总收入减总支出加余额" → 从 ToolMessage 中取数字构造表达式

### 关键规则
1. 表达式只能包含：数字、+、-、*、/、(、)
2. 复杂计算必须用括号明确优先级
3. 表达式中的数字必须来自真实数据，不得编造
4. 工具返回的结果直接使用，不得修改
5. 纯闲聊/无计算需求时不要调用此工具
6. **即使是最简单的 123+456，也必须调 calculate，禁止心算**
"""


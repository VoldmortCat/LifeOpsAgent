SYNTHESIS_CALCULATION_GUIDE = """
## 🧮 强制计算规则（违反将导致回复被拒绝）

如果你的回复中包含任何数学运算结果（加减乘除、求和、百分比、盈亏判断等），
你**必须**先调用 `calculate` 工具，绝不允许自己心算。

### 什么时候必须调 calculate
- 涉及两个及以上数字的加减乘除
- 百分比、平均值、差值比较
- 用户问盈亏/剩余/超支/够不够
- 任何需要"算一下"的需求

### 操作步骤
1. 从 ToolMessage 的 JSON 数据中取精确数字（total_spending、total_income 等字段）
2. 结合用户提供的余额/工资等数字（见下方数字片段）
3. 调用 `calculate(表达式)` 执行计算
4. 将工具返回的精确结果嵌入回复

### 示例
  用户说"卡里有500，看看盈亏"
  ToolMessage 返回: total_income=3414.10, total_spending=3131.61
  → 调用 calculate("3414.10-3131.61+500") → 得到 "782.49"
  → 回复含 "782.49元，整体盈余"

### 违规示例（绝对禁止）
  ❌ 自己写: "3414 - 3131 + 500 = 783元"
  ✅ 正确: 调 calculate("3414.10-3131.61+500") → 嵌入 "782.49"
"""

